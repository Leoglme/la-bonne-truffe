class DepartmentSeeder:
    """Creates the missing departments and fills the verified Centrale Canine identifiers."""

    def run(self, db: Session) -> int:
        """
        Seed the departments; existing rows are kept, a missing ``scc_term_id`` is filled when verified.

        Args:
            db: Database session.

        Returns:
            Number of departments created.
        """
        existing_by_code = {department.code: department for department in db.query(Department).all()}
        created_count = 0
        for code, name, region in FRENCH_DEPARTMENTS:
            department = existing_by_code.get(code)
            if department is None:
                department = Department(code=code, name=name, region=region)
                db.add(department)
                created_count += 1
            if department.scc_term_id is None and code in VERIFIED_SCC_TERM_IDS:
                department.scc_term_id = VERIFIED_SCC_TERM_IDS[code]
        db.commit()
        return created_count
